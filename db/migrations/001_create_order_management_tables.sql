BEGIN;

CREATE TABLE public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_reference VARCHAR(32) NOT NULL UNIQUE,
    submission_key UUID NOT NULL UNIQUE,

    customer_name VARCHAR(150) NOT NULL,
    customer_mobile VARCHAR(15) NOT NULL,
    customer_email VARCHAR(254),

    delivery_address TEXT NOT NULL,
    delivery_city VARCHAR(100) NOT NULL,
    delivery_state VARCHAR(100) NOT NULL,
    delivery_pincode VARCHAR(6) NOT NULL,

    subtotal NUMERIC(12,2) NOT NULL,
    shipping_amount NUMERIC(12,2) NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'Requested',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT orders_status_check CHECK (
        status IN (
            'Requested',
            'Confirmed',
            'Packed',
            'Shipped',
            'Delivered',
            'Rejected',
            'Cancelled'
        )
    ),

    CONSTRAINT orders_pincode_check CHECK (
        delivery_pincode ~ '^[1-9][0-9]{5}$'
    ),

    CONSTRAINT orders_amount_check CHECK (
        subtotal >= 0
        AND shipping_amount >= 0
        AND total_amount = subtotal + shipping_amount
    )
);

CREATE TABLE public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id),
    product_id BIGINT,
    product_name TEXT NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    quantity INTEGER NOT NULL,
    line_total NUMERIC(12,2) NOT NULL,

    CONSTRAINT order_items_quantity_check CHECK (quantity > 0),
    CONSTRAINT order_items_price_check CHECK (
        unit_price >= 0
        AND line_total = unit_price * quantity
    )
);

CREATE TABLE public.order_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES public.orders(id),

    status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    method VARCHAR(30),
    verified_amount NUMERIC(12,2),
    transaction_reference TEXT,
    verified_at TIMESTAMPTZ,
    verified_by VARCHAR(150),
    admin_notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT order_payments_status_check CHECK (
        status IN ('Pending', 'Paid', 'Refunded')
    ),

    CONSTRAINT order_payments_amount_check CHECK (
        verified_amount IS NULL OR verified_amount >= 0
    )
);

CREATE TABLE public.order_shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES public.orders(id),

    courier_name VARCHAR(150),
    tracking_number VARCHAR(150),
    dispatched_at TIMESTAMPTZ,
    expected_delivery_date DATE,
    delivered_at TIMESTAMPTZ,
    admin_notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id),

    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    event_type VARCHAR(30) NOT NULL DEFAULT 'status_change',

    changed_by VARCHAR(150) NOT NULL,
    reason TEXT,
    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.order_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id),

    notification_type VARCHAR(30) NOT NULL,
    channel VARCHAR(20) NOT NULL DEFAULT 'WhatsApp',
    status VARCHAR(20) NOT NULL DEFAULT 'Sent',

    marked_sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    marked_sent_by VARCHAR(150) NOT NULL,
    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.order_number_counters (
    order_year INTEGER PRIMARY KEY,
    last_number BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT order_number_positive_check CHECK (
        last_number >= 0
    )
);

-- Indexes for dashboard filtering and historical records

CREATE INDEX idx_orders_status_created
    ON public.orders(status, created_at DESC, id DESC);

CREATE INDEX idx_orders_created
    ON public.orders(created_at DESC, id DESC);

CREATE INDEX idx_orders_payment_lookup
    ON public.order_payments(status);

CREATE INDEX idx_order_items_order
    ON public.order_items(order_id);

CREATE INDEX idx_order_status_history_order
    ON public.order_status_history(order_id, created_at DESC);

CREATE INDEX idx_order_notifications_order
    ON public.order_notifications(order_id, created_at DESC);

COMMIT;
